#!/usr/bin/env python3
"""Configure native Hyprland touchpad gestures without an input daemon."""
import argparse
from contextlib import contextmanager
from datetime import datetime
import fcntl
import hashlib
import json
import math
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile

PLUGIN_ID = "okuma.dev_touchpad4omarchy"
HEADER = "-- Generated by OkumaTouchpad. Edit settings through the plugin or CLI.\n"
BEGIN = "-- BEGIN OkumaTouchpad loader"
END = "-- END OkumaTouchpad loader"
ACTIONS = ["none", "bar-hide", "bar-show", "bar-toggle", "launchpad-open", "launchpad-close", "launchpad-toggle"]


def field(key, label, group, kind, default, **options):
    return dict(key=key, label=label, group=group, kind=kind, default=default, **options)


FIELDS = [
    field("naturalScroll", "Natural scrolling (content follows fingers)", "Touchpad", "boolean", True),
    field("tapToClick", "Tap to click", "Touchpad", "boolean", True),
    field("tapButtonMap", "Tap button order", "Touchpad", "enum", "lrm", choices=["lrm", "lmr"]),
    field("clickfinger", "Use finger count for physical clicks", "Touchpad", "boolean", True),
    field("disableWhileTyping", "Disable touchpad while typing", "Touchpad", "boolean", True),
    field("threeFingerDrag", "Three-finger dragging", "Touchpad", "boolean", True),
    field("scrollFactor", "Global touchpad scroll multiplier", "Touchpad", "number", 1.0, minimum=0.1, maximum=5.0),
    field("workspaceSwipe", "Continuous horizontal workspace swipe", "Workspaces", "boolean", True),
    field("workspaceFingers", "Workspace swipe finger count", "Workspaces", "enum", 4, choices=[3, 4]),
    field("workspaceInvert", "Invert horizontal workspace direction", "Workspaces", "boolean", False),
    field("workspaceDistance", "Workspace swipe distance", "Workspaces", "number", 300, minimum=50, maximum=2000, integer=True),
    field("workspaceCancelRatio", "Workspace cancellation ratio", "Workspaces", "number", 0.5, minimum=0.0, maximum=1.0),
    field("numericNeighbors", "Use adjacent numeric workspaces", "Workspaces", "boolean", True),
    field("createEmptyWorkspaces", "Allow empty neighboring workspaces", "Workspaces", "boolean", True),
    field("verticalFingers", "Vertical swipe finger count", "Vertical swipes", "enum", 4, choices=[3, 4]),
    field("swipeUp", "Swipe up action", "Vertical swipes", "enum", "bar-hide", choices=ACTIONS),
    field("swipeDown", "Swipe down action", "Vertical swipes", "enum", "bar-show", choices=ACTIONS),
    field("pinchFingers", "Primary pinch finger count", "Pinch", "enum", 4, choices=[3, 4]),
    field("pinchIn", "Pinch inward action", "Pinch", "enum", "none", choices=ACTIONS),
    field("pinchOut", "Spread outward action", "Pinch", "enum", "none", choices=ACTIONS),
    field("threeFingerSpread", "Extra three-finger spread action (may conflict with dragging)", "Pinch", "enum", "none", choices=ACTIONS),
    field("pinchThreshold", "Pinch scale change threshold", "Pinch", "number", 0.10, minimum=0.10, maximum=0.50),
    field("launchpadPlugin", "Launchpad plugin ID", "Integration", "string", "okuma.dev_launchpad4omarchy"),
]
DEFAULTS = {f["key"]: f["default"] for f in FIELDS}
# Comments, quoted strings, and Lua long strings must not become executable tokens.
TOKENS = re.compile(r'''--\[(=*)\[.*?\]\1\]|--[^\n]*|"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'|\[(=*)\[.*?\]\2\]|[A-Za-z_][A-Za-z_0-9]*|\d+|[^\s]''', re.S)


def validate(data):
    if not isinstance(data, dict):
        raise ValueError("Settings must be a JSON object")
    unknown = set(data) - set(DEFAULTS)
    if unknown:
        raise ValueError("Unknown settings: " + ", ".join(sorted(unknown)))
    result = DEFAULTS | data
    for f in FIELDS:
        value = result[f["key"]]
        kind = f["kind"]
        valid = True
        if kind == "boolean":
            valid = type(value) is bool
        elif kind == "enum":
            valid = type(value) is type(f["default"]) and value in f["choices"]
        elif kind == "number":
            valid = (type(value) in (int, float) and math.isfinite(value)
                     and f["minimum"] <= value <= f["maximum"]
                     and (not f.get("integer") or int(value) == value))
        elif kind == "string":
            valid = isinstance(value, str) and len(value) <= 100 and bool(re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]*", value)) and ".." not in value
        if not valid:
            raise ValueError(f"Invalid value for {f['key']}: {value!r}")
    return result


def lua_string(value):
    return '"' + ''.join('\\\\' if c == '\\' else '\\"' if c == '"' else f'\\{ord(c):03d}' if ord(c) < 32 else c for c in value) + '"'


def lua_value(value):
    if type(value) is bool:
        return "true" if value else "false"
    if type(value) in (int, float):
        return str(value)
    return lua_string(value)


def command(action, settings):
    plugin = settings["launchpadPlugin"]
    return {
        "none": None,
        "bar-hide": "omarchy toggle bar on",
        "bar-show": "omarchy toggle bar off",
        "bar-toggle": "omarchy toggle bar",
        "launchpad-open": f"omarchy-shell shell summon {plugin} '{{}}'",
        "launchpad-close": f"omarchy-shell shell hide {plugin}",
        "launchpad-toggle": f"omarchy-shell shell toggle {plugin} '{{}}'", 
    }[action]


def render(data):
    s = validate(data)
    touchpad = {
        "natural_scroll": s["naturalScroll"], "tap_to_click": s["tapToClick"],
        "tap_button_map": s["tapButtonMap"], "clickfinger_behavior": s["clickfinger"],
        "disable_while_typing": s["disableWhileTyping"],
        "drag_3fg": int(s["threeFingerDrag"]), "scroll_factor": s["scrollFactor"],
    }
    gestures = {
        "workspace_swipe_invert": s["workspaceInvert"], "workspace_swipe_distance": s["workspaceDistance"],
        "workspace_swipe_cancel_ratio": s["workspaceCancelRatio"],
        "workspace_swipe_use_r": s["numericNeighbors"], "workspace_swipe_create_new": s["createEmptyWorkspaces"],
    }
    lines = [HEADER.rstrip(), "hl.config({", "  input = { touchpad = {"]
    lines += [f"    {key} = {lua_value(value)}," for key, value in touchpad.items()]
    lines += ["  } },", "  gestures = {"]
    lines += [f"    {key} = {lua_value(value)}," for key, value in gestures.items()]
    lines += ["  },", "})"]
    if s["workspaceSwipe"]:
        lines.append(f'hl.gesture({{ fingers = {s["workspaceFingers"]}, direction = "horizontal", action = "workspace" }})')
    for key, direction in (("swipeUp", "up"), ("swipeDown", "down")):
        cmd = command(s[key], s)
        if cmd:
            lines.append(f'hl.gesture({{ fingers = {s["verticalFingers"]}, direction = "{direction}", action = function() hl.exec_cmd({lua_string(cmd)}) end }})')
    def pinch(fingers, inward, outward):
        if inward == outward == "none":
            return
        lines.extend(["do", "  local fired = false", "  local function update(e)",
                      "    if fired or not e.scale then return end", "    local command"])
        for op, scale, action in (("<=", 1 - s["pinchThreshold"], inward), (">=", 1 + s["pinchThreshold"], outward)):
            cmd = command(action, s)
            if cmd:
                lines.append(f"    if e.scale {op} {scale:.6f} then command = {lua_string(cmd)} end")
        lines.extend(["    if command then fired = true; hl.exec_cmd(command) end", "  end",
                      f'  hl.gesture({{ fingers = {fingers}, direction = "pinch", action = {{',
                      "    start = function(e) fired = false; update(e) end,",
                      "    update = update,", "    finish = function(e) fired = false end,", "  } })", "end"])
    pinch(s["pinchFingers"], s["pinchIn"], s["pinchOut"])
    if s["pinchFingers"] != 3:
        pinch(3, "none", s["threeFingerSpread"])
    source = "\n".join(lines) + "\n"
    digest = hashlib.sha256(source.encode()).hexdigest()
    return source + f'_G.okuma_touchpad_digest = "{digest}"\n', digest


def warnings(settings):
    result = []
    if settings["threeFingerDrag"]:
        if (settings["workspaceSwipe"] and settings["workspaceFingers"] == 3) or settings["verticalFingers"] == 3 or settings["pinchFingers"] == 3 or settings["threeFingerSpread"] != "none":
            result.append("Three-finger gestures may conflict with three-finger dragging; test on real hardware.")
    if settings["pinchFingers"] == 3 and settings["threeFingerSpread"] != "none":
        result.append("Extra three-finger spread is ignored: the primary three-finger pinch already owns this event.")
    result.append("Natural scrolling controls touchpad scrolling, not workspace swipe direction or mouse wheels.")
    return result


def remove_loader(text):
    if text.count(BEGIN) != text.count(END) or text.count(BEGIN) > 1:
        raise ValueError("Malformed OkumaTouchpad loader block")
    if BEGIN not in text:
        return text
    start, finish = text.index(BEGIN), text.index(END)
    if finish < start:
        raise ValueError("Invalid loader block order")
    finish += len(END)
    if text[finish:finish + 1] == "\n":
        finish += 1
    return text[:start] + text[finish:]


def add_loader(text, path):
    clean = remove_loader(text)
    return clean + ("" if clean.endswith("\n") else "\n") + BEGIN + "\n" + f"dofile({lua_string(str(path))})\n" + END + "\n"


def tokens(text):
    return [m.group() for m in TOKENS.finditer(text) if not m.group().startswith("--")]


def conflicts(folder, target):
    """Conservatively refuse all other literal hl.gesture registrations."""
    found = []
    for path in sorted(folder.rglob("*.lua")):
        if path == target:
            continue
        words = tokens(path.read_text())
        if any(words[i:i + 4] == ["hl", ".", "gesture", "("] for i in range(len(words) - 3)):
            found.append(str(path))
    return found


def run(*args):
    result = subprocess.run(list(map(str, args)), capture_output=True, text=True, timeout=20)
    output = (result.stdout + result.stderr).strip()
    if result.returncode or (args[:2] == ("hyprctl", "eval") and output != "ok"):
        raise RuntimeError(output or f"Command failed: {args[0]}")
    return output


def preflight(settings):
    for executable in ("hyprctl", "omarchy", "omarchy-shell"):
        if not shutil.which(executable):
            raise RuntimeError(f"Required command not found: {executable}")
    if run("hyprctl", "configerrors"):
        raise RuntimeError("Resolve existing Hyprland configuration errors first")
    try:
        run("hyprctl", "eval", 'assert(type(hl.config) == "function" and type(hl.gesture) == "function", "Native Lua gesture API unavailable")')
    except RuntimeError as error:
        raise RuntimeError("This session requires Hyprland's native Lua hl.config/hl.gesture API "
                           "(tested on 0.56.2). Legacy hyprland.conf sessions are not supported. "
                           "No settings were saved. Details: " + str(error)) from error
    return integration_warnings(settings)


def integration_warnings(settings):
    """Optional panels must never prevent independent touchpad settings applying."""
    actions = [settings[k] for k in ("swipeUp", "swipeDown", "pinchIn", "pinchOut")]
    if settings["pinchFingers"] != 3:
        actions.append(settings["threeFingerSpread"])
    if any(a.startswith("launchpad-") for a in actions):
        try:
            status = run("omarchy-shell", "shell", "call", settings["launchpadPlugin"], "status", "")
            if status in {"open", "closed"}:
                return []
        except (OSError, RuntimeError, subprocess.SubprocessError):
            pass
        return [f"Launchpad {settings['launchpadPlugin']} is unavailable. Only Launchpad actions "
                "will be inactive until it is enabled; touchpad, workspace and bar settings can still apply. "
                "Select none for unused Launchpad actions."]
    return []


def safe_path(path):
    for part in (path, *path.parents):
        if part.is_symlink():
            raise ValueError(f"Refusing symlink configuration path: {part}")


def atomic_write(path, text):
    safe_path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    mode = (path.stat().st_mode & 0o777) if path.exists() else 0o600
    fd, temporary = tempfile.mkstemp(prefix="." + path.name, dir=path.parent)
    try:
        with os.fdopen(fd, "w") as stream:
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
        os.chmod(temporary, mode)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


@contextmanager
def locked(home):
    directory = home / "omarchy"
    safe_path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    lock = directory / ".okuma-touchpad.lock"
    safe_path(lock)
    with lock.open("a") as stream:
        fcntl.flock(stream, fcntl.LOCK_EX | fcntl.LOCK_NB)
        yield


def transact(changes, verify):
    """Back up every changed file, then roll back all owned changes on failure."""
    originals = {}
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S-%f")
    for path, text in changes.items():
        safe_path(path)
        original = path.read_text() if path.exists() else None
        if original != text:
            originals[path] = original
            if original is not None:
                backup = path.with_name(path.name + ".bak.okuma-touchpad." + stamp)
                shutil.copy2(path, backup)
    try:
        for path in originals:
            text = changes[path]
            if text is None:
                path.unlink()
            else:
                atomic_write(path, text)
        verify()
    except Exception:
        for path, original in originals.items():
            if original is None:
                path.unlink(missing_ok=True)
            else:
                atomic_write(path, original)
        try:
            run("hyprctl", "reload")
        except (OSError, RuntimeError, subprocess.SubprocessError):
            pass
        raise


def paths(home):
    return home / "hypr/hyprland.lua", home / "hypr/okuma-touchpad.lua", home / "omarchy/okuma-touchpad.json"


def read_settings(path, override=None):
    if override is not None:
        return validate(json.loads(override))
    return validate(json.loads(path.read_text()) if path.exists() else {})


def apply(home, settings):
    main, target, config = paths(home)
    for path in (main, target, config):
        safe_path(path)
    if not main.is_file():
        raise ValueError(f"Expected Hyprland Lua entry point: {main}. Legacy hyprland.conf sessions "
                         "are not supported; no settings were saved.")
    if target.exists() and not target.read_text().startswith(HEADER):
        raise ValueError(f"Refusing to overwrite an unowned file: {target}")
    existing = conflicts(home / "hypr", target)
    if existing:
        raise ValueError("Existing gesture registrations require manual migration:\n" + "\n".join(existing))
    notices = preflight(settings)
    source, digest = render(settings)
    def verify():
        run("hyprctl", "eval", "_G.okuma_touchpad_digest = nil")
        run("hyprctl", "reload")
        errors = run("hyprctl", "configerrors")
        if errors:
            raise RuntimeError(errors)
        run("hyprctl", "eval", f'assert(_G.okuma_touchpad_digest == "{digest}", "OkumaTouchpad loader was not executed")')
        verify_effective(settings)
    transact({target: source, main: add_loader(main.read_text(), target),
              config: json.dumps(settings, indent=2) + "\n"}, verify)
    return notices


def verify_effective(settings):
    """Verify live options as well as parsing, including when diagnosing saved profiles."""
    expected = {
        "input:touchpad:natural_scroll": ("bool", settings["naturalScroll"]),
        "input:touchpad:tap_to_click": ("bool", settings["tapToClick"]),
        "input:touchpad:tap_button_map": ("str", settings["tapButtonMap"]),
        "input:touchpad:clickfinger_behavior": ("bool", settings["clickfinger"]),
        "input:touchpad:disable_while_typing": ("bool", settings["disableWhileTyping"]),
        "input:touchpad:drag_3fg": ("int", int(settings["threeFingerDrag"])),
        "input:touchpad:scroll_factor": ("float", settings["scrollFactor"]),
        "gestures:workspace_swipe_invert": ("bool", settings["workspaceInvert"]),
        "gestures:workspace_swipe_distance": ("int", settings["workspaceDistance"]),
        "gestures:workspace_swipe_cancel_ratio": ("float", settings["workspaceCancelRatio"]),
        "gestures:workspace_swipe_use_r": ("bool", settings["numericNeighbors"]),
        "gestures:workspace_swipe_create_new": ("bool", settings["createEmptyWorkspaces"]),
    }
    for option, (kind, value) in expected.items():
        actual = json.loads(run("hyprctl", "-j", "getoption", option)).get(kind)
        matches = (type(actual) in (int, float) and math.isclose(actual, value, rel_tol=1e-5)) if kind == "float" else actual == value
        if not matches:
            raise RuntimeError(f"Effective setting mismatch: {option}: expected {value!r}, got {actual!r}. "
                               "Check later overrides and per-device configuration.")


def application_status(home, settings):
    _, target, config = paths(home)
    if not config.is_file() or not target.is_file():
        return dict(applied=False, message="Settings have not been applied on this device. Use Apply and save.")
    try:
        digest = render(settings)[1]
        run("hyprctl", "eval", f'assert(_G.okuma_touchpad_digest == "{digest}", "Saved profile is not loaded; apply again")')
        verify_effective(settings)
    except (ValueError, OSError, RuntimeError, subprocess.SubprocessError) as error:
        return dict(applied=False, message=str(error))
    return dict(applied=True, message="Saved settings are loaded; global touchpad options verified. "
                "Physical gesture recognition and per-device overrides still require testing.")


def uninstall(home):
    main, target, _ = paths(home)
    for path in (main, target):
        safe_path(path)
    if not main.is_file():
        raise ValueError(f"Missing Hyprland entry point: {main}")
    if target.exists() and not target.read_text().startswith(HEADER):
        raise ValueError("Refusing to delete an unowned generated file")
    def verify():
        run("hyprctl", "reload")
        errors = run("hyprctl", "configerrors")
        if errors:
            raise RuntimeError(errors)
    transact({main: remove_loader(main.read_text()), target: None}, verify)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=["describe", "preview", "apply", "remove", "doctor"])
    parser.add_argument("--settings-json", help="Complete or partial settings object; omitted fields use defaults")
    parser.add_argument("--config-home", type=Path, default=Path(os.environ.get("XDG_CONFIG_HOME") or Path.home() / ".config"))
    args = parser.parse_args()
    try:
        home = args.config_home.expanduser().absolute()
        _, target, config = paths(home)
        settings = read_settings(config, args.settings_json) if args.action != "remove" else None
        if args.action == "describe":
            print(json.dumps(dict(settings=settings, fields=FIELDS, warnings=warnings(settings),
                                  status=application_status(home, settings))))
        elif args.action == "preview":
            print(render(settings)[0], end="")
            print("\n".join("Warning: " + w for w in warnings(settings)), file=sys.stderr)
        elif args.action == "doctor":
            print("Device listing is not proof of physical gesture support.")
            print("Conflicting user Lua files:", json.dumps(conflicts(home / "hypr", target)))
            print("\n".join(warnings(settings)))
            print("Hyprland version:\n" + run("hyprctl", "version"))
            print("Configuration root:", home)
            for notice in preflight(settings):
                print("Warning:", notice)
            print(run("hyprctl", "devices", "-j"))
            state = application_status(home, settings)
            print(state["message"])
            if not state["applied"]:
                raise RuntimeError("Managed settings are not active. Review the diagnostics above, then Apply and save.")
        else:
            with locked(home):
                if args.action == "apply":
                    notices = apply(home, settings)
                    print("Settings applied and saved. Loader and global touchpad options verified. "
                          "Test physical gestures on this device.")
                    print("\n".join("Warning: " + w for w in notices + warnings(settings)))
                else:
                    uninstall(home)
                    print("Managed gestures removed. Settings and timestamped backups were retained.")
    except (ValueError, OSError, RuntimeError, subprocess.SubprocessError) as error:
        parser.exit(1, f"OkumaTouchpad: {error}\n")


if __name__ == "__main__":
    main()
